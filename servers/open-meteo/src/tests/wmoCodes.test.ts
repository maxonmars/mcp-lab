import { describe, expect, it } from "vitest";
import { describeWeatherCode } from "../weather/wmoCodes.ts";

describe("describeWeatherCode", () => {
  it.each([
    [0, "ясно"],
    [1, "преимущественно ясно"],
    [2, "переменная облачность"],
    [3, "пасмурно"],
    [45, "туман"],
    [48, "изморозь (осаждающийся туман)"],
    [51, "лёгкая морось"],
    [53, "умеренная морось"],
    [55, "сильная морось"],
    [56, "лёгкая переохлаждённая морось"],
    [57, "сильная переохлаждённая морось"],
    [61, "небольшой дождь"],
    [63, "умеренный дождь"],
    [65, "сильный дождь"],
    [66, "лёгкий переохлаждённый дождь"],
    [67, "сильный переохлаждённый дождь"],
    [71, "небольшой снег"],
    [73, "умеренный снег"],
    [75, "сильный снег"],
    [77, "снежные зёрна"],
    [80, "небольшие ливни"],
    [81, "умеренные ливни"],
    [82, "сильные ливни"],
    [85, "небольшой снегопад ливневого характера"],
    [86, "сильный снегопад ливневого характера"],
    [95, "гроза"],
    [96, "гроза с небольшим градом"],
    [99, "гроза с сильным градом"],
  ])("сопоставляет код %s с описанием %s", (code, description) => {
    expect(describeWeatherCode(code)).toBe(description);
  });

  it("честно называет неизвестный код, не выдумывая состояние", () => {
    expect(describeWeatherCode(777)).toBe("неизвестный код погоды Open-Meteo (777)");
  });
});
